// 出生位置：左上角 (x,y)，y 可以为负（缓冲区）
// 用 10 列棋盘居中，方块 4x4 矩阵左上放在 x=3
export const SPAWN_X = 3;
export const SPAWN_Y = 0;

// SRS 踢墙表 — JLSTZ 用
// 按旋转前 → 旋转后的方向，每组 5 个候选偏移 [dx, dy]
// dy 为 SRS 定义中 y 向上为正，我们转换为"y 向下为正"，因此取负
type Kicks = Array<[number, number]>;

const KICKS_JLSTZ: Record<string, Kicks> = {
  '0->1': [ [0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2] ],
  '1->0': [ [0, 0], [ 1, 0], [ 1,-1], [0,  2], [ 1,  2] ],
  '1->2': [ [0, 0], [ 1, 0], [ 1,-1], [0,  2], [ 1,  2] ],
  '2->1': [ [0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2] ],
  '2->3': [ [0, 0], [ 1, 0], [ 1, 1], [0, -2], [ 1, -2] ],
  '3->2': [ [0, 0], [-1, 0], [-1,-1], [0,  2], [-1,  2] ],
  '3->0': [ [0, 0], [-1, 0], [-1,-1], [0,  2], [-1,  2] ],
  '0->3': [ [0, 0], [ 1, 0], [ 1, 1], [0, -2], [ 1, -2] ],
};

const KICKS_I: Record<string, Kicks> = {
  '0->1': [ [0, 0], [-2, 0], [ 1, 0], [-2,-1], [ 1, 2] ],
  '1->0': [ [0, 0], [ 2, 0], [-1, 0], [ 2, 1], [-1,-2] ],
  '1->2': [ [0, 0], [-1, 0], [ 2, 0], [-1, 2], [ 2,-1] ],
  '2->1': [ [0, 0], [ 1, 0], [-2, 0], [ 1,-2], [-2, 1] ],
  '2->3': [ [0, 0], [ 2, 0], [-1, 0], [ 2, 1], [-1,-2] ],
  '3->2': [ [0, 0], [-2, 0], [ 1, 0], [-2,-1], [ 1, 2] ],
  '3->0': [ [0, 0], [ 1, 0], [-2, 0], [ 1,-2], [-2, 1] ],
  '0->3': [ [0, 0], [-1, 0], [ 2, 0], [-1, 2], [ 2,-1] ],
};

export function getKicks(type: TetrominoType, from: Rotation, to: Rotation): Kicks {
  const key = `${from}->${to}`;
  if (type === 'O') return [[0, 0]];
  if (type === 'I') return KICKS_I[key] ?? [[0, 0]];
  return KICKS_JLSTZ[key] ?? [[0, 0]];
}

// 返回方块在棋盘上的绝对占格 [row, col]
export function getBlocks(piece: ActivePiece): Array<[number, number]> {
  const shape = SHAPES[piece.type][piece.rotation];
  const cells: Array<[number, number]> = [];
  for (let r = 0; r < 4; r++) {
    for (let c = 0; c < 4; c++) {
      if (shape[r][c]) {
        cells.push([piece.y + r, piece.x + c]);
      }
    }
  }
  return cells;
}

export function spawnPiece(type: TetrominoType): ActivePiece {
  return { type, rotation: 0, x: SPAWN_X, y: SPAWN_Y };
}
